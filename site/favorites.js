/*
 * Starred documents.
 *
 * Two deliberate constraints shape this:
 *
 *  - Stars are keyed by `documents.ref` (f<fileId> / i<itemId> / m<meetingId>),
 *    never by `documents.id`. The id is an autoincrement assigned at build time,
 *    so a single new meeting shifts every id below it and a saved star would
 *    silently point at a different document a week later.
 *
 *  - Nothing is stored anywhere but the visitor's own browser, and the only
 *    thing stored is a list of public-record document identifiers. No accounts,
 *    no user ids, no server. Sharing puts those identifiers in a URL *fragment*,
 *    which browsers never transmit - so even the host of a shared link never
 *    sees which documents it names.
 */

const KEY = 'boardbook:favorites:v1';

/** Beyond this a "collection" is really a bulk export, and share URLs get unwieldy. */
export const MAX_STARS = 500;

/** Refs are generated by the build, but a shared link is untrusted input. */
const VALID_REF = /^[fim][0-9]+$/;

/*
 * Every localStorage access is guarded. Access itself throws in some privacy
 * modes and in sandboxed frames - not just reads of missing keys - so a failure
 * here must degrade to "no stars" rather than breaking the page.
 */
function readRaw() {
  try {
    return globalThis.localStorage?.getItem(KEY) ?? null;
  } catch {
    return null;
  }
}

function writeRaw(value) {
  try {
    globalThis.localStorage?.setItem(KEY, value);
    return true;
  } catch {
    return false;
  }
}

/** @returns {string[]} starred refs, most recently added last */
export function loadStars() {
  const raw = readRaw();
  if (!raw) return [];
  try {
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed.filter((r) => VALID_REF.test(r)) : [];
  } catch {
    return [];
  }
}

/** @returns {boolean} whether the write succeeded (storage can be unavailable) */
export function saveStars(refs) {
  const clean = [...new Set(refs.filter((r) => VALID_REF.test(r)))].slice(0, MAX_STARS);
  return writeRaw(JSON.stringify(clean));
}

export const isStarred = (ref, stars = loadStars()) => stars.includes(ref);

/**
 * Add or remove a star.
 * @returns {{stars: string[], starred: boolean, full: boolean, stored: boolean}}
 */
export function toggleStar(ref) {
  if (!VALID_REF.test(ref)) {
    return { stars: loadStars(), starred: false, full: false, stored: false };
  }
  const stars = loadStars();
  const at = stars.indexOf(ref);

  if (at !== -1) {
    stars.splice(at, 1);
    return { stars, starred: false, full: false, stored: saveStars(stars) };
  }
  if (stars.length >= MAX_STARS) {
    return { stars, starred: false, full: true, stored: false };
  }
  stars.push(ref);
  return { stars, starred: true, full: false, stored: saveStars(stars) };
}

export function clearStars() {
  return saveStars([]);
}

/* ---------- sharing ---------- */

const toBase64Url = (s) => globalThis.btoa(s).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
const fromBase64Url = (s) => globalThis.atob(s.replace(/-/g, '+').replace(/_/g, '/'));

/**
 * Encode refs for a URL fragment. Refs are ASCII by construction, so plain
 * base64url is safe and keeps the result readable-ish in a browser history.
 */
export function encodeStars(refs) {
  const clean = refs.filter((r) => VALID_REF.test(r));
  if (!clean.length) return '';
  return toBase64Url(clean.join(' '));
}

/** Decode a shared collection. Returns [] for anything malformed. */
export function decodeStars(encoded) {
  if (!encoded) return [];
  try {
    return [...new Set(fromBase64Url(encoded).split(' ').filter((r) => VALID_REF.test(r)))]
      .slice(0, MAX_STARS);
  } catch {
    return [];
  }
}

/** Merge a shared collection into the visitor's own stars. */
export function mergeStars(incoming) {
  const stars = loadStars();
  const added = incoming.filter((r) => VALID_REF.test(r) && !stars.includes(r));
  const merged = [...stars, ...added].slice(0, MAX_STARS);
  saveStars(merged);
  return { stars: merged, added: added.length };
}
